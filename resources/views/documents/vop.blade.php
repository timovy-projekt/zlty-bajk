    <h1>Všeobecné obchodné podmienky</h1>
    <div class="sub">služby požičovne bicyklov Bajkuj v meste</div>

    <h2>1. Úvodné ustanovenia</h2>
    <ol>
        <li>Tieto podmienky upravujú prenájom bicyklov prevádzkovateľom Bajkuj v meste, Trnava (ďalej „prevádzkovateľ").</li>
        <li>Zákazníkom je osoba, ktorá sa zaregistruje a využíva služby prevádzkovateľa.</li>
        <li>Podmienky sú súčasťou každej nájomnej zmluvy.</li>
    </ol>

    <h2>2. Registrácia a používateľský účet</h2>
    <ol>
        <li>Služby môže využívať osoba, ktorá dovŕšila 15 rokov a overila svoj e-mail.</li>
        <li>Zákazník vo veku 15 až 17 rokov uvedie pri registrácii údaje svojho zákonného zástupcu.</li>
        <li>Zákazník uvádza pravdivé údaje a chráni svoje prihlasovacie údaje pred zneužitím.</li>
    </ol>

    <h2>3. Žiadosť o prenájom</h2>
    <ol>
        <li>Overený zákazník podáva cez aplikáciu žiadosť o prenájom bicykla.</li>
        <li>Prevádzkovateľ žiadosť schváli alebo zamietne podľa dostupnosti bicyklov v sklade.</li>
        <li>Nájomná zmluva vzniká schválením žiadosti.</li>
    </ol>

    <h2>4. Cena a platobné podmienky</h2>
    <ol>
        <li>Cena prenájmu sa riadi platným cenníkom zverejneným na webovej stránke.</li>
        <li>Prevádzkovateľ môže požadovať zálohu, ktorá sa vráti pri vrátení bicykla bez poškodenia.</li>
    </ol>

    <h2>5. Prevzatie a vrátenie bicykla</h2>
    <ol>
        <li>Zákazník pri prevzatí skontroluje stav bicykla a prípadné nedostatky ihneď nahlási.</li>
        <li>Bicykel sa vracia v dohodnutom čase a na dohodnutom mieste.</li>
        <li>Pri omeškaní účtuje prevádzkovateľ nájomné aj za čas omeškania.</li>
    </ol>

    <h2>6. Povinnosti zákazníka</h2>
    <ol>
        <li>Používať bicykel v súlade s jeho určením a pravidlami cestnej premávky.</li>
        <li>Nepožičať bicykel tretej osobe a nepoužiť ho na pretekárske alebo komerčné účely.</li>
        <li>Bicykel pri parkovaní riadne zamknúť.</li>
        <li>Stratu, krádež alebo poškodenie bezodkladne nahlásiť prevádzkovateľovi.</li>
    </ol>

    <h2>7. Zodpovednosť za škodu</h2>
    <ol>
        <li>Zákazník zodpovedá za poškodenie, stratu alebo krádež bicykla počas nájmu.</li>
        <li>Bežné opotrebenie sa za poškodenie nepovažuje.</li>
    </ol>

    <h2>8. Reklamácie</h2>
    <ol>
        <li>Nedostatky služby alebo bicykla môže zákazník uplatniť na e-mailovej adrese info@bajkujvmeste.sk.</li>
        <li>Prevádzkovateľ reklamáciu posúdi a odpovie bez zbytočného odkladu.</li>
    </ol>

    <h2>9. Ochrana osobných údajov</h2>
    <ol>
        <li>Spracúvanie osobných údajov je popísané v samostatnom dokumente Informácie o spracúvaní osobných údajov (GDPR).</li>
    </ol>

    <h2>10. Záverečné ustanovenia</h2>
    <ol>
        <li>Prevádzkovateľ môže tieto podmienky zmeniť. Aktuálne znenie je dostupné v aplikácii.</li>
        <li>Právne vzťahy sa riadia právnym poriadkom Slovenskej republiky.</li>
    </ol>

