    <h2>1. Prevádzkovateľ</h2>
    <p>Prevádzkovateľom osobných údajov je Bajkuj v meste, Trnava, e-mail: info@bajkujvmeste.sk (ďalej „prevádzkovateľ").</p>

    <h2>2. Aké údaje spracúvame</h2>
    <ul>
        <li><strong>Údaje zákazníka:</strong> meno, priezvisko, e-mail, telefón, adresa, dátum narodenia, číslo občianskeho preukazu (nepovinné).</li>
        <li><strong>Údaje zákonného zástupcu</strong> (pri zákazníkoch vo veku 15 až 17 rokov): meno, priezvisko, e-mail, telefón, adresa, dátum narodenia, číslo občianskeho preukazu (nepovinné).</li>
        <li><strong>Údaje o prenájme:</strong> prenajaté bicykle, termíny prenájmu, žiadosti o prenájom.</li>
        <li><strong>Prihlasovacie údaje:</strong> e-mail a heslo uložené v zašifrovanej podobe (hash).</li>
    </ul>

    <h2>3. Účel a právny základ</h2>
    <ul>
        <li>Registrácia a správa používateľského účtu, uzavretie a plnenie nájomnej zmluvy (čl. 6 ods. 1 písm. b GDPR).</li>
        <li>Overenie veku a získanie údajov zákonného zástupcu pri maloletých zákazníkoch (čl. 6 ods. 1 písm. c a f GDPR).</li>
        <li>Ochrana pred škodou, vymáhanie pohľadávok a evidencia prenajatého majetku (čl. 6 ods. 1 písm. f GDPR).</li>
        <li>Plnenie zákonných povinností, napríklad účtovných a daňových (čl. 6 ods. 1 písm. c GDPR).</li>
    </ul>

    <h2>4. Doba uchovávania</h2>
    <ul>
        <li>Údaje o účte uchovávame po dobu jeho existencie, najviac [počet] rokov po poslednom prenájme.</li>
        <li>Zmluvy a súvisiace doklady uchovávame po dobu určenú osobitnými predpismi.</li>
        <li>Po uplynutí doby uchovávania sa údaje vymažú alebo anonymizujú.</li>
    </ul>

    <h2>5. Komu údaje poskytujeme</h2>
    <ul>
        <li>Údaje neposkytujeme tretím stranám na marketingové účely.</li>
        <li>Prístup k nim majú oprávnení administrátori prevádzkovateľa a poskytovatelia technických služieb (hosting a databáza), ktorí ich spracúvajú v našom mene.</li>
        <li>Orgánom verejnej moci ich poskytneme, len ak to vyžaduje zákon.</li>
    </ul>

    <h2>6. Vaše práva</h2>
    <p>Máte právo na:</p>
    <ul>
        <li>prístup k svojim osobným údajom a získanie ich kópie,</li>
        <li>opravu nesprávnych alebo neúplných údajov,</li>
        <li>vymazanie údajov, ak nie sú potrebné na uvedené účely,</li>
        <li>obmedzenie spracúvania a vznesenie námietky,</li>
        <li>prenosnosť údajov,</li>
        <li>podanie sťažnosti dozornému orgánu, ktorým je Úrad na ochranu osobných údajov Slovenskej republiky.</li>
    </ul>
    <p>Svoje práva môžete uplatniť na e-mailovej adrese info@bajkujvmeste.sk.</p>

    <h2>7. Bezpečnosť údajov</h2>
    <p>Údaje chránime primeranými technickými a organizačnými opatreniami. Heslá sa ukladajú v zašifrovanej podobe a prístup k databáze je obmedzený.</p>

